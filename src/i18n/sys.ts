export function sy(locale: Locale, key: string): string {
  return PL[key] ?? t(locale, key);
}

export function syp(locale: Locale, key: string, params: Record<string, string | number>): string {
  let s = sy(locale, key);
  for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

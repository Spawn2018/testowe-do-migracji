export function s7(locale: Locale, key: string): string {
  return PL[key] ?? t(locale, key);
}

export function s7p(locale: Locale, key: string, params: Record<string, string | number>): string {
  let s = s7(locale, key);
  for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

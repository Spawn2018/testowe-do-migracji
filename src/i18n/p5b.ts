export function fb(locale: Locale, key: string): string {
  return PL[key] ?? t(locale, key);
}

export function fbp(locale: Locale, key: string, params: Record<string, string | number>): string {
  let s = fb(locale, key);
  for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
